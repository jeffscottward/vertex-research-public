"""Pins the holes of the qc-ports data the plan was tested on: prints golive/tested_gaps.py.

    cd services/research && python -m golive.pin --data <qc-ports data directory> > golive/tested_gaps.py

The generator refuses a run when the data lacks a value on an older day that the pinned data has a
value for (generator.check_history). Every hole in the printed file is a gap the generator accepts
from then on. So pin only after checking the data, and read the diff of tested_gaps.py before
committing it: a new hole there is a decision to trade on a history with that gap.

Exit codes: 0 the module is printed; 1 the data directory cannot be read or a file in it is not
qc-ports data (the reason on stderr); 2 usage (argparse).
"""
from __future__ import annotations

import argparse
import contextlib
import sys
from pathlib import Path

from strategies.qc_ports import study

from .generator import data_gaps

__all__ = ["module_text", "main"]


def module_text(gaps: dict[str, tuple], through: str) -> str:
    """The source of golive/tested_gaps.py for `gaps` (generator.data_gaps) of data that ends on `through`."""
    lines = [
        f'"""The holes of the qc-ports data the plan was tested on (data through {through}).',
        "",
        "Generated by `python -m golive.pin`; do not edit by hand. generator.check_history refuses a run",
        "when the data lacks a value on an older day that this data has a value for.",
        "",
        "name -> (first day, holes): a series by its id, the bars of an ETF as `<ETF> bars`. A hole is a",
        "run of consecutive days without a value (first day, last day): for a series, trading days of the",
        "calendar; for bars, days on which any ETF of the data has a bar.",
        '"""',
        "",
        f'PINNED_THROUGH = "{through}"',
        "",
        "TESTED_GAPS: dict[str, tuple[str, tuple[tuple[str, str], ...]]] = {",
    ]
    for name, (first, holes) in gaps.items():
        if not holes:
            lines.append(f'    "{name}": ("{first}", ()),')
            continue
        lines.append(f'    "{name}": ("{first}", (')
        lines.extend(f'        ("{start}", "{end}"),' for start, end in holes)
        lines.append("    )),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv=None, stdout=None, stderr=None) -> int:
    stdout, stderr = stdout or sys.stdout, stderr or sys.stderr
    parser = argparse.ArgumentParser(prog="python -m golive.pin", description=__doc__.splitlines()[0])
    parser.add_argument("--data", required=True, type=Path, help="qc-ports data directory (read only)")
    args = parser.parse_args(argv)
    try:
        # stdout carries the module and nothing else: a print of the loader goes to stderr.
        with contextlib.redirect_stdout(stderr):
            dataset = study.load_study_data(args.data.expanduser()).dataset
    except (OSError, KeyError, ValueError) as error:  # a directory or a file that is not qc-ports data
        print(f"golive.pin: the data directory {args.data} cannot be read: {error}", file=stderr)
        return 1
    stdout.write(module_text(data_gaps(dataset), dataset.calendar[-1]))
    return 0


if __name__ == "__main__":  # pragma: no cover - the module entry point; main() is tested
    sys.exit(main())
