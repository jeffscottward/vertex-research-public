// Owner decision (2026-11-08): the captions and transcripts of the Academy's database courses
// (QuantFinanceToGo) stay out of this repository. `bun run vertex:academy:import` reads them from the
// knowledge base where it runs; tests, CI and the E2E seed use synthetic fixture sources. This gate fails
// when a sources snapshot, a knowledge-base reel note or a non-synthetic fixture is committed.
import { execFile } from "node:child_process";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

import { describe, expect, it } from "vitest";

import { COURSE_LIST } from "../../packages/academy/src/courses.ts";
import {
  FIXTURE_TEXT,
  SOURCES as QUANTFINANCETOGO_FIXTURE,
} from "../academy/lessons/quantfinancetogo/sources.fixture.ts";

const root = fileURLToPath(new URL("../../", import.meta.url));
const execFileAsync = promisify(execFile);
const git = (args: readonly string[]) =>
  execFileAsync("git", [...args], { cwd: root, maxBuffer: 64 * 1024 * 1024 });

const DATABASE_COURSES = COURSE_LIST.filter(
  (course) => course.store === "database"
).map((course) => course.id);
// The only sources file a database course may commit.
const FIXTURE_FILE = "sources.fixture.ts";
const SNAPSHOT_MARKER =
  "Generated by scripts/academy/build-sources.ts from the";

describe("private Academy sources", () => {
  it("tracks no sources snapshot of a database course and no knowledge-base reel note", async () => {
    const { stdout } = await git(["ls-files", "-z"]);
    const tracked = stdout.split("\0").filter((path) => path !== "");
    const snapshots = tracked.filter((path) =>
      DATABASE_COURSES.some((course) => {
        const prefix = `scripts/academy/lessons/${course}/`;
        if (!path.startsWith(prefix)) return false;
        const name = path.slice(prefix.length);
        return name.startsWith("sources") && name !== FIXTURE_FILE;
      })
    );
    expect(snapshots).toEqual([]);
    expect(tracked.filter((path) => /(^|\/)ig-[^/]+\.md$/u.test(path))).toEqual(
      []
    );
  });

  it("tracks no module written by the old sources snapshot generator", async () => {
    // git grep exits 1 when nothing matches.
    await expect(
      git([
        "grep",
        "-l",
        "-F",
        SNAPSHOT_MARKER,
        "--",
        ".",
        ":(exclude)scripts/ci/private-academy-sources.test.ts",
      ])
    ).rejects.toMatchObject({ code: 1 });
  });

  it("ignores a locally built QuantFinanceToGo snapshot", async () => {
    await expect(
      git([
        "check-ignore",
        "-q",
        "--no-index",
        "scripts/academy/lessons/quantfinancetogo/sources.generated.ts",
      ])
    ).resolves.toBeDefined();
  });

  it("keeps the QuantFinanceToGo fixture synthetic: placeholder caption and transcript only", () => {
    expect(QUANTFINANCETOGO_FIXTURE.length).toBeGreaterThan(0);
    for (const source of QUANTFINANCETOGO_FIXTURE as readonly Readonly<
      Record<string, unknown>
    >[]) {
      expect(source["caption"]).toBe(FIXTURE_TEXT);
      expect(source["transcript"]).toEqual([{ start: 0, text: FIXTURE_TEXT }]);
    }
  });
});
