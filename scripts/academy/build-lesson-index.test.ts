import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import type * as Academy from "../../packages/academy/src/index.ts";
import {
  buildLessonIndex,
  type LessonIndexOptions,
  runLessonIndexEntrypoint,
} from "./build-lesson-index.ts";

// Scene faults keyed by lesson slug: real specs never produce them, so tests inject them here.
const faults = vi.hoisted(() => ({
  nonFinite: new Set<string>(),
  thrown: new Map<string, unknown>(),
}));

vi.mock("../../packages/academy/src/index.ts", async (importOriginal) => {
  const actual = await importOriginal<typeof Academy>();
  return {
    ...actual,
    buildScene: (...args: Parameters<typeof Academy.buildScene>) => {
      const [lesson] = args;
      // The script passes whole specs although buildScene only declares the scene.
      const slug = "slug" in lesson ? String(lesson.slug) : "";
      if (faults.thrown.has(slug)) throw faults.thrown.get(slug);
      const scene = actual.buildScene(...args);
      if (!faults.nonFinite.has(slug)) return scene;
      return {
        ...scene,
        panels: scene.panels.map((panel, index) =>
          index === 0
            ? {
                ...panel,
                series: panel.series.map((series) => ({
                  ...series,
                  points: [...series.points, [0, Number.NaN]],
                })),
              }
            : panel
        ),
      };
    },
  };
});

const SLUG_A = "covered-call-asymmetry-fixes";
const SLUG_B = "high-iv-needs-low-hv";
const REAL_SPECS = join(
  import.meta.dirname,
  "../../packages/academy/src/lessons/specs"
);

interface Spec {
  slug: string;
  sourceId: string;
  [key: string]: unknown;
}
const readSpec = (slug: string): Spec =>
  JSON.parse(readFileSync(join(REAL_SPECS, `${slug}.json`), "utf8")) as Spec;

let root: string;
let specs: string;
let out: string;
let stdout: string[];
let stderr: string[];

const options = (): LessonIndexOptions => ({
  root,
  stdout: { write: (text: string) => stdout.push(text) },
  stderr: { write: (text: string) => stderr.push(text) },
});

const generated = (files: readonly string[]) =>
  [
    "// Generated by scripts/academy/build-lesson-index.ts. Do not edit by hand.",
    ...files.map((file, index) =>
      file.endsWith(".ts")
        ? `import { spec as spec${index} } from "./specs/${file}";`
        : `import spec${index} from "./specs/${file}" with { type: "json" };`
    ),
    "",
    `export const LESSON_SPECS: readonly unknown[] = [${files.map((_, index) => `spec${index}`).join(", ")}];`,
    "",
  ].join("\n");

const errorLines = () => stderr.join("").trimEnd().split("\n");

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "academy-lessons-"));
  specs = join(root, "packages/academy/src/lessons/specs");
  out = join(root, "packages/academy/src/lessons/specs.generated.ts");
  mkdirSync(specs, { recursive: true });
  writeFileSync(
    join(root, "packages/academy/src/lessons/sources.json"),
    JSON.stringify([
      { sourceId: readSpec(SLUG_A).sourceId },
      { sourceId: readSpec(SLUG_B).sourceId },
    ])
  );
  for (const slug of [SLUG_A, SLUG_B])
    copyFileSync(join(REAL_SPECS, `${slug}.json`), join(specs, `${slug}.json`));
  writeFileSync(join(specs, "notes.txt"), "not a spec");
  stdout = [];
  stderr = [];
  faults.nonFinite.clear();
  faults.thrown.clear();
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

const addBrokenSpecs = () => {
  writeFileSync(join(specs, "bad.json"), JSON.stringify({ slug: 1 }));
  // Spec A again under another name: wrong file name and a reused source.
  copyFileSync(join(REAL_SPECS, `${SLUG_A}.json`), join(specs, "renamed.json"));
  writeFileSync(
    join(specs, "unknown-source.json"),
    JSON.stringify({
      ...readSpec(SLUG_B),
      slug: "unknown-source",
      sourceId: "missing-source",
    })
  );
};

describe("buildLessonIndex", () => {
  it("writes the generated index for valid specs", async () => {
    expect(await buildLessonIndex([], options())).toBe(0);
    expect(readFileSync(out, "utf8")).toBe(
      generated([`${SLUG_A}.json`, `${SLUG_B}.json`])
    );
    expect(stdout).toEqual(["2 lesson specs valid\n"]);
    expect(stderr).toEqual([]);
  });

  it("checks the generated index without writing it", async () => {
    writeFileSync(out, "stale");
    expect(await buildLessonIndex(["--check"], options())).toBe(1);
    expect(errorLines()).toEqual([
      "specs.generated.ts is stale; run bun scripts/academy/build-lesson-index.ts",
    ]);
    expect(readFileSync(out, "utf8")).toBe("stale");

    stderr = [];
    writeFileSync(out, generated([`${SLUG_A}.json`, `${SLUG_B}.json`]));
    expect(await buildLessonIndex(["--check"], options())).toBe(0);
    expect(stderr).toEqual([]);
    expect(stdout).toEqual(["2 lesson specs valid\n"]);
  });

  it("reports invalid specs and still writes the index", async () => {
    addBrokenSpecs();
    expect(await buildLessonIndex([], options())).toBe(1);
    const lines = errorLines();
    expect(lines[0]).toMatch(/^bad\.json: \S+ .+/u);
    expect(lines.slice(1)).toEqual([
      "renamed.json: slug covered-call-asymmetry-fixes must match the file name",
      `renamed.json: sourceId ${readSpec(SLUG_A).sourceId} already used by ${SLUG_A}.json`,
      "unknown-source.json: unknown sourceId missing-source",
    ]);
    expect(readFileSync(out, "utf8")).toBe(
      generated([
        "bad.json",
        `${SLUG_A}.json`,
        `${SLUG_B}.json`,
        "renamed.json",
        "unknown-source.json",
      ])
    );
    expect(stdout).toEqual([]);
  });

  it("reports scenes with non-finite points or failures", async () => {
    faults.nonFinite.add(SLUG_A);
    faults.thrown.set(SLUG_B, new Error("boom"));
    expect(await buildLessonIndex([], options())).toBe(1);
    const lines = errorLines();
    const nonFinite = lines.slice(0, -1);
    for (const line of nonFinite)
      expect(line).toMatch(
        new RegExp(
          `^${SLUG_A}\\.json: non-finite point in \\S+/\\S+ at t=(0|0\\.5|1)$`,
          "u"
        )
      );
    for (const t of ["0", "0.5", "1"])
      expect(nonFinite.some((line) => line.endsWith(` at t=${t}`))).toBe(true);
    expect(lines.at(-1)).toBe(`${SLUG_B}.json: scene failed: boom`);

    stderr = [];
    faults.nonFinite.clear();
    faults.thrown.set(SLUG_B, "plain failure");
    expect(await buildLessonIndex([], options())).toBe(1);
    expect(errorLines()).toEqual([
      `${SLUG_B}.json: scene failed: plain failure`,
    ]);
  });

  it("validates only the listed specs and writes nothing", async () => {
    addBrokenSpecs();
    expect(await buildLessonIndex(["--only", SLUG_B], options())).toBe(0);
    expect(stdout).toEqual(["1 lesson specs valid\n"]);
    expect(existsSync(out)).toBe(false);

    // A listed spec also conflicts with unlisted specs that share its source.
    expect(
      await await buildLessonIndex(
        ["--only", `${SLUG_A}.json,missing`],
        options()
      )
    ).toBe(1);
    expect(errorLines()).toEqual([
      `${SLUG_A}.json: sourceId ${readSpec(SLUG_A).sourceId} already used by renamed.json`,
      "missing spec files: missing",
    ]);
    expect(existsSync(out)).toBe(false);
  });

  it("treats a trailing --only as an empty selection", async () => {
    expect(await buildLessonIndex(["--only"], options())).toBe(1);
    expect(errorLines()).toEqual(["missing spec files:"]);
  });
});

describe("buildLessonIndex with a second course", () => {
  const QFTG_SOURCES =
    "packages/academy/src/lessons/sources.quantfinancetogo.generated.ts";
  const writeQftgSources = (sources: readonly unknown[]) =>
    writeFileSync(
      join(root, QFTG_SOURCES),
      `export const SOURCES = ${JSON.stringify(sources)};\n`
    );
  const qftgSpec = (slug: string, sourceId = "QftgReel01") => ({
    ...readSpec(SLUG_B),
    course: "quantfinancetogo",
    slug,
    sourceId,
  });
  const addCourse = (specsByName: Record<string, unknown>) => {
    writeQftgSources([{ sourceId: "QftgReel01" }, { sourceId: "QftgReel02" }]);
    mkdirSync(join(specs, "quantfinancetogo"));
    for (const [name, spec] of Object.entries(specsByName))
      writeFileSync(
        join(specs, "quantfinancetogo", name),
        `export const spec = ${JSON.stringify(spec)};\n`
      );
  };

  it("indexes course folders after the default course", async () => {
    addCourse({ "binomial-tree.ts": qftgSpec("binomial-tree") });
    expect(await buildLessonIndex([], options())).toBe(0);
    expect(readFileSync(out, "utf8")).toBe(
      generated([
        `${SLUG_A}.json`,
        `${SLUG_B}.json`,
        "quantfinancetogo/binomial-tree.ts",
      ])
    );
    expect(stdout).toEqual(["3 lesson specs valid\n"]);
    // --only finds a spec in a course folder by its slug.
    stdout = [];
    expect(await buildLessonIndex(["--only", "binomial-tree"], options())).toBe(
      0
    );
    expect(stdout).toEqual(["1 lesson specs valid\n"]);
  });

  it("refuses a wrong course, another course's source, a reused slug or a source listed twice", async () => {
    addCourse({
      "no-course.ts": { ...qftgSpec("no-course"), course: undefined },
      "dyr-source.ts": qftgSpec("dyr-source", readSpec(SLUG_A).sourceId),
      [`${SLUG_B}.ts`]: qftgSpec(SLUG_B, "QftgReel02"),
      // A JSON file in a TypeScript course folder is not a spec.
      "stray.json": qftgSpec("stray"),
    });
    writeQftgSources([
      { sourceId: "QftgReel01" },
      { sourceId: "QftgReel02" },
      { sourceId: readSpec(SLUG_B).sourceId },
    ]);
    expect(await buildLessonIndex([], options())).toBe(1);
    expect(errorLines()).toEqual([
      `sources.quantfinancetogo.generated.ts: sourceId ${readSpec(SLUG_B).sourceId} already listed by sources.json`,
      `${SLUG_B}.json: slug ${SLUG_B} also used by quantfinancetogo/${SLUG_B}.ts`,
      `quantfinancetogo/dyr-source.ts: sourceId ${readSpec(SLUG_A).sourceId} is a dyr source, not quantfinancetogo`,
      `quantfinancetogo/dyr-source.ts: sourceId ${readSpec(SLUG_A).sourceId} already used by ${SLUG_A}.json`,
      `quantfinancetogo/${SLUG_B}.ts: slug ${SLUG_B} also used by ${SLUG_B}.json`,
      "quantfinancetogo/no-course.ts: course dyr does not match its folder (course quantfinancetogo)",
      "quantfinancetogo/no-course.ts: sourceId QftgReel01 is a quantfinancetogo source, not dyr",
    ]);
  });
});

describe("runLessonIndexEntrypoint", () => {
  it("does nothing when imported", async () => {
    const exitState: { exitCode?: number } = {};
    await runLessonIndexEntrypoint({
      isMain: undefined,
      argv: ["bun", "build-lesson-index.ts"],
      options: options(),
      exitState,
    });
    await runLessonIndexEntrypoint({
      isMain: false,
      argv: ["bun", "build-lesson-index.ts"],
      options: options(),
      exitState,
    });
    expect(exitState).toEqual({});
    expect(existsSync(out)).toBe(false);
    expect(import.meta.main).toBeFalsy();
  });

  it("runs with the arguments after the runtime and script", async () => {
    const exitState: { exitCode?: number } = {};
    writeFileSync(out, "stale");
    const entry = (...args: string[]) =>
      runLessonIndexEntrypoint({
        isMain: true,
        argv: ["bun", "scripts/academy/build-lesson-index.ts", ...args],
        options: options(),
        exitState,
      });
    await entry("--check");
    expect(exitState.exitCode).toBe(1);
    await entry();
    expect(exitState.exitCode).toBe(0);
    expect(readFileSync(out, "utf8")).toBe(
      generated([`${SLUG_A}.json`, `${SLUG_B}.json`])
    );
  });
});
